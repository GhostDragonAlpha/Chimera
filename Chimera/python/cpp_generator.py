"""
C++ Generation Engine for the Chimera Procedural Game Generator.
Handles generation of .h and .cpp files to Source/Chimera/.
"""

import os
from config import *


def ensure_directories():
    """Ensure all required directories exist."""
    dirs_to_create = [
        GameConfiguration.source_dir(),
        os.path.join(GameConfiguration.chimera_root(), "Source", "Chimera", "Generated"),
        os.path.join(GameConfiguration.content_dir(), "ProceduralGenerated"),
        os.path.join(GameConfiguration.content_dir(), "GeneratedLevels")
    ]

    for dir_path in dirs_to_create:
        os.makedirs(dir_path, exist_ok=True)


def generate_cpp_header_file(class_name, base_class, includes=None):
    """Generate a C++ header file."""
    if includes is None:
        includes = ["CoreMinimal.h"]

    header_content = f"// Generated by ProceduralGameGenerator\n"
    header_content += f"#pragma once\n\n"
    header_content += f'#include "CoreMinimal.h"\n'

    for inc in includes:
        if inc != "CoreMinimal.h":
            header_content += f'#include "{inc}"\n'

    header_content += f"\nclass CHIMERA_API U{class_name} : public {base_class}\n"
    header_content += "{\n"
    header_content += f"\tGENERATED_BODY()\n\n"
    header_content += "public:\n"
    header_content += f"\tU{class_name}(const FObjectInitializer& ObjectInitializer);\n\n"
    header_content += "protected:\n"
    header_content += "\t// Override functions here\n\n"
    header_content += "private:\n"
    header_content += "};\n"

    file_path = os.path.join(GameConfiguration.source_dir(), f"{class_name}.h")
    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(header_content)

    return file_path


def generate_cpp_source_file(class_name, includes=None):
    """Generate a C++ source file."""
    if includes is None:
        includes = [f"{class_name}.h"]

    source_content = f"// Generated by ProceduralGameGenerator\n"
    source_content += f'#include "{class_name}.h"\n'

    for inc in includes:
        if inc != f"{class_name}.h":
            source_content += f'#include "{inc}"\n'

    source_content += f"\nU{class_name}::U{class_name}(const FObjectInitializer& ObjectInitializer)\n"
    source_content += "\t: Super(ObjectInitializer)\n"
    source_content += "{\n"
    source_content += "\t// Constructor code here\n"
    source_content += "}\n"

    file_path = os.path.join(GameConfiguration.source_dir(), f"{class_name}.cpp")
    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(source_content)

    return file_path


def generate_procedural_generator_component():
    """Generate the main procedural generator C++ component."""
    # Generate header
    header_path = generate_cpp_header_file(
        class_name="ProceduralGeneratorComponent",
        base_class="UActorComponent",
        includes=["CoreMinimal.h", "GameFramework/Actor.h"]
    )

    # Generate source
    source_path = generate_cpp_source_file(
        class_name="ProceduralGeneratorComponent",
        includes=["ProceduralGeneratorComponent.h"]
    )

    return header_path, source_path


