    def _generate_procedural_texture(self, description: str, style: str, color_palette: str, 
                                       output_path: Path) -> Optional[Path]:
        """Generate procedural texture as fallback."""
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Create a simple PPM or placeholder file
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(f"// Procedural Texture Generated by Chimera\n")
            f.write(f"Description: {description}\n")
            f.write(f"Style: {style}\n")
            f.write(f"ColorPalette: {color_palette}\n")
            f.write(f"Provider: procedural_fallback\n")
            
        return output_path

    def _create_placeholder_image(self, prompt: str, provider_type: str, output_path: Path) -> Optional[Path]:
        """Create placeholder image file with metadata."""
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Generate hash-based filename for deduplication
        prompt_hash = hashlib.md5(prompt.encode()).hexdigest()[:8]
        base_name = f"tex_{provider_type}_{prompt_hash}"
        
        placeholder_path = output_path.with_name(f"{base_name}.uasset")
        
        with open(placeholder_path, 'w', encoding='utf-8') as f:
            f.write(f"/Script/Engine.Texture2D\n")
            f.write(f'{{\n')
            f.write(f'\tAssetName="{placeholder_path.name.replace(".uasset", "")}"\n')
            f.write(f'\tDescription="{prompt}"\n')
            f.write(f'\tProvider="{provider_type}"\n')
            f.write(f'}}\n')
            
        return placeholder_path

