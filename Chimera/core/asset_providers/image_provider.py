class StableDiffusionImageProvider(AssetGenerationProvider):
    """Text-to-image provider using Stable Diffusion API or local inference."""

    def __init__(self, config: Dict[str, Any] = None):
        super().__init__("stable_diffusion", config or {})
        
        self.provider_type = self.config.get("provider", "procedural")
        self.model = self.config.get("model", "sd-xl-base")
        self.prompt_prefix = self.config.get("prompt_prefix", "Unreal Engine texture, high quality, ")
        self.negative_prompt = self.config.get("negative_prompt", "low quality, blurry, distorted, ugly")
        self.resolution = tuple(self.config.get("resolution", [1024, 1024]))

    def _build_prompt(self, description: str, style: str, color_palette: str) -> str:
        """Build the generation prompt from DSL parameters."""
        base_prompt = f"{self.prompt_prefix}{description}"
        if style:
            base_prompt += f", style: {style}"
        if color_palette:
            base_prompt += f", color palette: {color_palette}"
        
        # Add texture-specific keywords
        base_prompt += ", seamless texture, 4k resolution, PBR materials"
        
        return base_prompt

    def generate_texture(self, description: str, style: str, color_palette: str, 
                         output_path: Path) -> Optional[Path]:
        """Generate texture using selected provider method."""
        prompt = self._build_prompt(description, style, color_palette)
        
        if self.provider_type == "stable_diffusion_local":
            return self._generate_sd_local(prompt, output_path)
        elif self.provider_type == "dalle_api":
            return self._generate_dalle(prompt, output_path)
        else:
            # Fallback to procedural/mock generation
            return self._generate_procedural_texture(description, style, color_palette, output_path)

    def _generate_sd_local(self, prompt: str, output_path: Path) -> Optional[Path]:
        """Generate using local Stable Diffusion inference."""
