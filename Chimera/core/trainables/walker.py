"""walker — a body that MOVES. The objective that cannot be faked.

THE WHOLE POINT
---------------
Static geometry cannot specify "creature". Three degenerate optima proved it on
2026-07-14 — a LOLLIPOP (boulder on a pole), a BLOB ON STILTS (minimally compliant),
and a MAST WITH OUTRIGGERS (legs sprawled flat on the ground, huge support polygon,
no mass, while a heavy rod held the centre of gravity high). Each scored beautifully.
Each was biologically absurd.

    Three exploits in a row is not a message about your parameters.
    It is a message about your FRAME.

A creature is not defined by how it STANDS. It is defined by what it DOES. So the
objective here is DISTANCE TRAVELLED, under real rigid-body physics, and it cannot be
gamed — because outriggers do not walk. A lollipop cannot chase anything.

THE CONTROLLER IS A CPG, AND THAT IS NOT A METAPHOR
---------------------------------------------------
Locomotion in real animals is generated by a Central Pattern Generator in the SPINAL
CORD, not the brain. A decerebrate cat still steps on a treadmill; a lamprey's swimming
rhythm survives complete removal of its head. So:

    angle_j(t) = offset_d + amp_d * sin(2*pi*f*t + phase_d + (pi if right else 0))

Parameters are indexed by tree DEPTH — every bone at the same level of the body shares
a rhythm — and LEFT and RIGHT limbs run in ANTIPHASE, which is exactly the
contralateral coupling that produces a quadruped gait. The genome grows the BODY and
encodes the RHYTHM, and they co-evolve. Karl Sims, 1994.

THE SKELETON *IS* THE MULTIBODY
-------------------------------
Bone.parent already gives a tree. That is precisely a Bullet articulated multibody:
one bone -> one link, one parent -> one revolute joint. The hinge axis is the natural
flexion axis, cross(parent_dir, bone_dir) — the plane the limb actually bends in. And
because the mesh is GROWN from the skeleton, the rig comes free: we know which bone
made every vertex.

FACTS ONLY. What makes a walk GOOD lives in docs/objectives/walker.json.
"""

from __future__ import annotations

import math
import random
