"""MAT2-A08 report generator (house G2/G3/G9).

report.md is GENERATED from bound artifacts only - parameter_envelope.json,
qualification_receipt.json, evidence/falsifier_receipt.json and the evidence
snapshots.  Zero hand-transcribed numbers: every literal is rendered from the
artifacts at their stored precision, so lint_report_numbers.py traces each
one.  The generator FAILS FIRST (named refusal codes) when an artifact is
missing, off-schema, or stale, and re-runs the named-check suite and the
verification gates, refusing to write a report over a red gate.

No wall-clock value enters the report (byte-identical regeneration).
"""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

