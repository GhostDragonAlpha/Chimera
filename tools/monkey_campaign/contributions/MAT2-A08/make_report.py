SYS_PY = sys.executable

DOC_SCHEMA = "chimera.a08_parameter_envelope.v1"
RECEIPT_SCHEMA = "chimera.qualification_receipt.v1"
FALSIFIER_SCHEMA = "chimera.a08_falsifiers.v1"

