"""spec_format.py -- the executable mathematical specification document
format (chimera.mathspec.spec.v1) and its validator.

mathspec lane wk-mathspec-core, phase 1. The format is BOUNDED to the first
supported class: ODE membranes with typed ports, coupled by declared
connections. Everything is validated structurally BEFORE anything runs:

  owned state vars + units            (exactly one owner per variable)
  parameters w/ domains + provenance  (measured | derived | synthetic)
  typed port inputs/outputs           (unit + sign convention + connection ref)
  evolution equations                 (restricted language, unit-checked)
  preconditions / invariants /        (predicate expressions, named codes)
  refusal conditions
  timestep + numerical-method         (declared admissible dt table, BEFORE
  assumptions                          any qualification run)
  required integration checks         (structural vs numerical-evidence)

Unit algebra: every declared unit decomposes to a dimension vector over
{length, mass, time, temperature}; + and - require equal dimensions; * and /
compose them. Offset-bearing units (degC) may be declared standalone but are
refused inside composition (E_SPEC_UNIT_OFFSET_COMPOSED). A dimension error is
a named refusal, never a warning.

This validator REUSES the frozen v2 port-contract law at the format level
(port ids, sign conventions, owner routing, exactly-one-ownership); the v2
CONTRACT instance itself is generated by spec_generate and validated by the
pinned PORT_CONTRACT_V2 (see spec_runtime). Nothing here validates physics
truth: synthetic provenance is declared as synthetic, and a MEASURED class
would require a store binding (E_SPEC_MEASURED_UNBOUND if absent).
"""
