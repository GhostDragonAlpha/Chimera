"""make_report.py -- MAT2-F05 report generator.

GENERATES report.md from evidence/checks.json (+ the capture manifest, the
validation receipt and the determinism receipt). Zero hand-transcribed
numbers: every figure is rendered from the bound receipts at their recorded
precision; report.md is refused if any required receipt is missing or off
identity (fail-first, named codes).

Run from this directory, after build + manifest + verify:
    python -B make_report.py
"""
from __future__ import annotations

import hashlib
import json
import math
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
EVIDENCE = HERE / "evidence"


class Refusal(ValueError):
    def __init__(self, code, detail=""):
        self.code, self.detail = code, str(detail)
        super().__init__(code + (": " + self.detail if detail else ""))


def require(condition, code, detail=""):
    if not condition:
        raise Refusal(code, detail)


def load_receipt(name):
    path = HERE / name if name == "checks_receipt.json" else EVIDENCE / name
    require(path.is_file(), "f05_report_receipt_missing", name)
    return json.loads(path.read_text(encoding="utf-8"))


def sha_file(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def num(x):
    """Render a number at its receipt precision (repr of the double)."""
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        return repr(x)
    return str(x)


def main():
    checks = load_receipt("checks_receipt.json")
    require(checks.get("schema") == "chimera.mat2_f05.terrain_envelope.v1",
            "f05_report_checks_schema", checks.get("schema"))
    require(checks.get("all_ok") is True, "f05_report_not_all_ok", None)
    require(checks.get("bites_all_bite") is True,
            "f05_report_bites_incomplete", None)
    manifest = load_receipt("capture_manifest.json")
    validation = load_receipt("validation_receipt.json")
    determinism = load_receipt("determinism.json")
    require(validation.get("structurally_valid") is True,
            "f05_report_capture_invalid", validation.get("fired"))
    require(determinism.get("determinism_byte_identical") is True,
            "f05_report_determinism", None)
    declaration = load_receipt("terrain_envelope_declaration.json")
    ident = checks["identity"]
    p2 = checks["P2_slope_envelope"]
    p3 = checks["P3_obstacle_envelope"]
    p4 = checks["P4_friction_envelope"]
    p5 = checks["P5_walk_plane_identity"]
    p6 = checks["P6_render_collision_correspondence"]

    require(sha_file(HERE / "checks_receipt.json") ==
            manifest["views"][0]["state_binding"]["sha256"],
            "f05_report_state_binding_stale", None)
    require(manifest["subject_sha256"] ==
            checks["envelope_declaration_sha256"],
            "f05_report_subject_stale", None)

    bound = p2["declared_bound_m_per_m"]
    bound_deg = math.degrees(math.atan(bound))
    worst = p2["derived_scene_max_grade_m_per_m"]
    worst_deg = p2["derived_scene_max_grade_deg"]
    route_max = p2["measured_route_max_slope_m_per_m"]
    min_clear = p3["measured_global_min_clearance_m"]
    margin = p2["bound_margin_m_per_m"]
    grid_read = p5["terrain_grid_bilinear_at_centre_m"]
    disagree = p5["disagreement_m"]
    margin_friction = p4["slope_friction_consistency"][
        "margin_factor_mu_over_tan"]
    counts = p6["outcome_counts_per_view"]

