    add("| declared-from-evidence discipline | the pin wall re-hashes %s "
        "in-tree sealed pins + %s evidence-store records at every run; the "
        "walk-plane identity binds the sealed W03 scene plane %s m to the "
        "authored composition plateau %s m exactly, and the terrain-law "
        "grid read at the same centre is %s m (disagreement %s m, the R3 "
        "class) | P1, P5 | PASS |"
        % (num(len([k for k in checks["pins"]
                    if checks["pins"][k]["origin"].startswith("in_tree")])),
           num(len([k for k in checks["pins"]
                    if checks["pins"][k]["origin"].startswith("store")])),
           num(p5["walk_scene_plane_m"]), num(p5["authored_plateau_m"]),
           num(grid_read), num(disagree)))
