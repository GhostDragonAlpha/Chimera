HERE = pathlib.Path(__file__).resolve().parent


def load(name):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def fmt(x) -> str:
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, float):
        return repr(x)
    return str(x)


def suite_counts() -> tuple[int, int]:
    out = subprocess.run(
        [sys.executable, "-B", "-m", "unittest", "test_g01_checks", "-v"],
        cwd=str(HERE), capture_output=True, text=True)
    text = out.stderr + out.stdout
    m = re.search(r"Ran (\d+) tests?", text)
    if not m:
        raise SystemExit(f"Refusal suite_counts_missing: {text[-400:]}")
    executed = int(m.group(1))
    skipped = len(re.findall(r"skipped", text))
    if out.returncode != 0:
        raise SystemExit(f"Refusal suite_not_green: {text[-800:]}")
    return executed, skipped


def main() -> int:
    r = load("feasibility_receipt.json")
    r2 = load("feasibility_receipt_rerun2.json")
    f = load("falsifier_receipt.json")
    d = r["derivation"]
    q = r["declared_quantities"]

    # two-pass bootstrap: provisional write (no counts numbers) -> suite ->
    # accounting receipt -> final write; the provisional and final differ ONLY
    # in the counts line.
    write_report(r, r2, f, None, None)
    executed, skipped = suite_counts()
    accounting = {
        "schema": "chimera.g01.checks_accounting.v1",
        "card": "MAT2-G01",
        "attempt_id": r["attempt_id"],
        "criteria_sha256": r["criteria_sha256"],
        "command": "python -B -m unittest test_g01_checks -v",
        "executed": executed,
        "skipped": skipped,
        "known_skips": "none (zero skips by design; no KNOWN_SKIPS entries)",
    }
    (HERE / "checks_accounting.json").write_bytes(
        (json.dumps(accounting, sort_keys=True, separators=(",", ":"),
                    ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8"))
    write_report(r, r2, f, executed, skipped)
    return 0


