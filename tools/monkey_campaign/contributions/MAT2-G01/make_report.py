"""MAT2-G01 report generator (house standard: GENERATED, zero hand-written numbers).

Reads feasibility_receipt.json, feasibility_receipt_rerun2.json and
falsifier_receipt.json, runs the named-check suite for the skip accounting,
and emits REPORT.md. Every number in the report is rendered from the receipts
at their printed precision; lint_report_numbers.py proves traceability.
"""
from __future__ import annotations

