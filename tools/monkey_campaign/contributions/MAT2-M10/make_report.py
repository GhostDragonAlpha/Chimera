def require(condition, code):
    if not condition:
        raise ValueError(code)


def load(name, required_keys=()):
    path = HERE / name
    require(path.exists(), 'm10_report_receipt_missing:' + name)
    doc = json.loads(path.read_text(encoding='utf-8'))
    for key in required_keys:
        require(key in doc,
                'm10_report_receipt_schema:' + name + ':' + key)
    return doc


