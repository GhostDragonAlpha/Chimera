def sha256_file(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def num(x):
    """Printed exactly as recorded (repr round-trips for floats)."""
    return repr(x) if isinstance(x, float) else str(x)


