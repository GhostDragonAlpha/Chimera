    w('| contact/support state is honestly declared | the declared support '
      'law (supported iff every available channel records stick AND phase '
      'hold) yields supported-hold for the SEVEN sealed stick cases and '
      'honest non-support for the five slip rows plus the zero-mu control '
      '(%s scenarios); the trunk anchor reaction and the two integrity '
      'signals (full-tick residual, reciprocity) are DECLARED slots; X4 | '
      'PASS |' % totals['scenarios'])
