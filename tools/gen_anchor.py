"""gen_anchor.py -- dream the anchor bear: one SDXL still that every local lane starts from.

The anchor is the ONLY single-image stage; every lane after it is multi-view synthesis,
so the bear's back is generated by a view-consistent model, never hallucinated by a
single-image-to-3D shortcut. Capture-protocol prompt: one object, centered, whole body
visible, plain dark background, fixed studio light -- the same discipline the Seedance
orbit prompt used, now as a still.

Usage:  .venv-gs/Scripts/python.exe tools/gen_anchor.py --out capture/genbear3 --seeds 4
"""
from __future__ import annotations

import argparse
from pathlib import Path

import torch
from diffusers import StableDiffusionXLPipeline

PROMPT = ("professional studio photograph of a single classic teddy bear, sitting upright, "
          "whole body visible and centered, facing the camera, soft brown fur, cream muzzle, "
          "seamless dark charcoal background, soft diffused studio lighting, photorealistic, "
          "sharp focus, 85mm lens")
NEGATIVE = ("text, watermark, extra limbs, deformed, multiple objects, cluttered background, "
            "white background, gradient background, shadow floor pattern, cropped, blurry, "
            "cartoon, illustration, 3d render look")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="capture/genbear3")
    ap.add_argument("--seeds", type=int, default=4)
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    pipe = StableDiffusionXLPipeline.from_pretrained(
        "stabilityai/stable-diffusion-xl-base-1.0",
        torch_dtype=torch.float16, variant="fp16", use_safetensors=True)
    pipe.to("cuda")

    for i in range(args.seeds):
        g = torch.Generator("cuda").manual_seed(1000 + i)
        img = pipe(PROMPT, negative_prompt=NEGATIVE, generator=g,
                   num_inference_steps=30, guidance_scale=7.0).images[0]
        p = out / f"anchor_{i:02d}.png"
        img.save(p)
        print(f"saved {p}")


if __name__ == "__main__":
    main()
