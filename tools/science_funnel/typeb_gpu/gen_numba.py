"""gen_numba.py -- emit walker_numba_gen.py from walker_gpu.py."""
import re
from translate_warp_to_numba import translate
from walker_numba import OF, OI, CF, CI
src = open('walker_gpu.py', encoding='utf-8').read()
body = translate(src)
body = body.replace('def tick_kernel(mdl, cst,', 'def tick_kernel(mdl, mdi, cst, csti,')
# module header + offset constants
hdr = ['"""AUTO-GENERATED by gen_numba.py from walker_gpu.py -- do not edit."""',
       'import math', 'import numpy as np', 'from numba import cuda, float64, int32, int64',
       'PI = 3.141592653589793', '']
for k, v in OF.items():
    hdr.append(f'OF_{k} = {v}')
for k, v in OI.items():
    hdr.append(f'OI_{k} = {v}')
for k, v in CF.items():
    hdr.append(f'CF_{k} = {v}')
for k, v in CI.items():
    hdr.append(f'CI_{k} = {v}')
hdr.append('')
out = '\n'.join(hdr) + '\n' + body
open('walker_numba_gen.py', 'w', encoding='utf-8').write(out)
print('generated', out.count('\n'), 'lines')
