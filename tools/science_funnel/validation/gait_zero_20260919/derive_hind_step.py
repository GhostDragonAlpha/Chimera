"""THE HIND STEP LAW's derivation (wave 28, receipt_wave28.json).

Mines the byte-reproduced wave-27 head run (d981bc04, the committed build,
scene e61ad3864472453f... regenerated byte-identically on this lane; the
mining instrument is a trace-only harness print, proven inert: its stdout
JSON is byte-identical to the committed build's) and derives, with zero new
free numbers, THE HIND STEP LAW:

  THE DEATH: the hind clock's lift slot fires into a STALL -- at
  phi >= TOE_OFF the pads are still live and loaded (the designed hind lift
  is kinematic only); the swing columns pull the joints against the planted
  paw, the ankle is driven onto its wall (headroom 0.0032 rad at tick 120),
  the paw skids (1.2455 m/s at 121), and the impact budget refuses at 122.

  THE TRIGGER, PICKED BY MEASUREMENT AMONG FIVE CANDIDATES (all mined):
  (a) the paw's absolute stance-end envelope (off_TO): NEVER CROSSED (the R
      bottoms 1.7 mm short -- the skid starts first). REJECTED.
  (b) the actual-vs-own-column recede: fires ~99-101 on the R but MISFIRES
      on the L (its paw rides 5.2 cm behind its column from the entry
      geometry). REJECTED.
  (c) THE CLOCK'S OWN LIFT SLOT + PADS STILL LIVE [SHIPPED]: the designed
      lift's own slot; a healthy lift departs within the slot's first
      ticks, a stalled (loaded) lift never does. Zero new constants.
  (d) the raw paw-slip bound (v_bound = mu*g*(1-CAPTURE_PHI)*T): MISFIRES
      on the DESIGNED residual (the R's settle face sustains > v_bound for
      ~35 ticks [55,90] admissibly). REJECTED.
  (e) the CoM-hull margin: a continuous regime from 84 (38 loaded exit
      ticks), no derivable threshold. REJECTED.

  THE INSTRUMENT NOTE: the status's contact position_m is the MIGRATING
  sole CoP (the lower heel/mp endpoint), not a fixed paw point -- the law's
  paw reference is the FK MIDPOINT of the declared heel/mp locals (0.031 m
  in the foot frame), computed from the trace's own joint angles through
  the planar chain FK (validated against the engine's own contact geometry
  at the reset state to 1.7 mm, and against the Assembly exactly).

Run:  python -B derive_hind_step.py <scene.json> <mining_trace.log> <out.json>
"""
import collections
import json
import math
import re
import sys

TOE_OFF = 0.68  # the controller's own constant


def main():
    scene = json.load(open(sys.argv[1], encoding='utf-8'))
    g = scene['gait_controller']
    r = g['recipe']
    m = g['model']
    z = r['zero_map_rad']
    tab = r['tables_rad']
    DUTY = float(r['duty_factor_sampled'])
    T = float(r['cycle_duration_s'])
    DT = 1.0 / float(r['tick_hz'])
    MU = float(r['contact_friction'])
    CPH = float(r['capture_step_phase'])
    rng = {k: v['range_rad'] for k, v in m['coordinates'].items()}
    seg = {b['name']: b for b in m['bodies']}
    L1 = abs(float(seg['shank_left']['joint']['parent_location_m'][1]))
    L2 = abs(float(seg['foot_left']['joint']['parent_location_m'][1]))
    pts = {p['name']: p for p in r['contact_points']}
    XM = 0.5 * (float(pts['left_heel']['point_m'][0]) + float(pts['left_mp_head']['point_m'][0]))
    V_BOUND = MU * 9.80665 * (1.0 - CPH) * T

    def interp(tt, phi):
        x = (phi % 1.0) * 20.0
        k = min(19, int(x))
        f = x - k
        return tt[k] * (1.0 - f) + tt[k + 1] * f

    def coloff(phi):
        a1 = z['hip'] + interp(tab['hip'], phi)
        a2 = a1 + z['knee'] + interp(tab['knee'], phi)
        ap = a2 + z['ankle'] + interp(tab['ankle'], phi)
        return L1 * math.sin(a1) + L2 * math.sin(a2) + XM * math.cos(ap)

    dv = {}
    dvj = collections.defaultdict(dict)
    dvp = {}
    for line in open(sys.argv[2], encoding='utf-8', errors='replace'):
        if line.startswith('[dv] '):
            t = int(re.search(r't=(\d+)', line).group(1))
            if t in dv:
                break
            ph = re.search(r'phL=([\d.eE+-]+) phR=([\d.eE+-]+)', line)
            pg = re.search(r'pang=([\d.eE+-]+)', line)
            bx = re.search(r'bx=([\d.eE+-]+)', line)
            dv[t] = (float(ph.group(1)), float(ph.group(2)), float(pg.group(1)), float(bx.group(1)))
        elif line.startswith('[dvj] '):
            t = int(re.search(r't=(\d+)', line).group(1))
            if t in dv and len(dvj[t]) == 8:
                continue
            k = int(re.search(r'k=(\d+)', line).group(1))
            dvj[t][k] = float(re.search(r'ang=([\d.eE+-]+)', line).group(1)) * math.pi / 180
        elif line.startswith('[dvp] '):
            t = int(re.search(r't=(\d+)', line).group(1))
            if t not in dv:
                continue
            k = int(re.search(r'k=(\d+)', line).group(1))
            q = re.search(r'gap=([\d.eE+-]+) rxn=([\d.eE+-]+) frc=([\d.eE+-]+) slip=([\d.eE+-]+)', line)
            dvp.setdefault(t, [None] * 4)[k] = tuple(float(q.group(i)) for i in (1, 2, 3, 4))

    ticks = sorted(dv)
    JK = {'L': (0, 1, 2, 3), 'R': (4, 5, 6, 7)}
    NM = ['hip_flexion_', 'knee_extension_', 'ankle_dorsiflexion_', 'MP_dorsiflexion_']

    def midoff(leg, t):
        qs = dvj[t]
        idx = JK[leg]
        a1 = qs[idx[0]]
        a2 = a1 + qs[idx[1]]
        return (L1 * math.sin(a1) + L2 * math.sin(a2) + XM * math.cos(a2 + qs[idx[2]]),
                a2 + qs[idx[2]])

    def headroom(leg, t):
        qs = dvj[t]
        hs = []
        for i in range(4):
            nm = NM[i] + ('left' if leg == 'L' else 'right')
            q = qs[JK[leg][i]]
            hs.append(min(q - rng[nm][0], rng[nm][1] - q))
        return min(hs)

    OFF_TD, OFF_TO = coloff(0.0), coloff(TOE_OFF)
    vw, vt = 0.0, -1
    for t in range(61, 122):
        v = (dv[t][3] - dv[t - 1][3]) / DT
        if v > vw:
            vw, vt = v, t
    KFLOOR = 2.0 * vw * DT
    LINE = OFF_TO + KFLOOR

    series = {}
    PK = {'L': (0, 1), 'R': (2, 3)}  # the declared POINT indices (the joints are JK)
    for t in ticks:
        phL, phR, pang, bx = dv[t]
        oL, apL = midoff('L', t)
        oR, apR = midoff('R', t)
        row = {}
        for lg, off, phi in (('L', oL, phL), ('R', oR, phR)):
            gap = min(dvp[t][PK[lg][0]][0], dvp[t][PK[lg][1]][0])
            slip = 0.0
            for k in PK[lg]:
                if dvp[t][k][0] <= 1e-5:
                    slip = max(slip, dvp[t][k][3])
            row[lg] = dict(off=off, phi=phi, gap=gap, slip=slip, touch=gap <= 1e-5)
        series[t] = row

    # the trigger candidates, measured
    cross_abs = {}
    cross_col = {}
    slot_fire = {}
    slip_first = {}
    adm_runs = []
    for lg in ('L', 'R'):
        cross_abs[lg] = next((t for t in ticks if series[t][lg]['touch'] and series[t][lg]['off'] <= LINE), None)
        cross_col[lg] = next((t for t in ticks if series[t][lg]['touch'] and
                              series[t][lg]['off'] <= coloff(series[t][lg]['phi']) - 0.0013), None)
        slot_fire[lg] = next((t for t in ticks if series[t][lg]['phi'] >= TOE_OFF and series[t][lg]['touch']), None)
        slip_first[lg] = next((t for t in ticks if series[t][lg]['touch'] and series[t][lg]['slip'] > V_BOUND), None)
    # the designed-residual runs above v_bound while admissible (phi < TOE_OFF)
    run = None
    for t in ticks:
        for lg in ('L', 'R'):
            s = series[t][lg]
            if s['touch'] and s['slip'] > V_BOUND and s['phi'] < TOE_OFF:
                if run is not None and run[0] == lg and run[2] == t - 1:
                    run[2] = t
                else:
                    if run is not None:
                        adm_runs.append(tuple(run))
                    run = [lg, t, t]
    if run is not None:
        adm_runs.append(tuple(run))

    t_air = math.ceil((T - DUTY) / DT)
    out = dict(
        schema='chimera.hind_step.v1',
        lane='agent/gait-wave28-hind-step', base='d981bc04',
        scene_sha256=scene['scene_sha256'],
        instrument='FK-midpoint paw reference (the CoP-based first instrument corrected; see the receipt)',
        envelope=dict(off_td_m=OFF_TD, off_to_m=OFF_TO, stance_span_m=OFF_TD - OFF_TO,
                      v_bound_m_s=V_BOUND),
        advance=dict(v_worst_m_s=vw, v_worst_tick=vt, k_step_floor_m=KFLOOR,
                     k_step_floor_form='2 * v_worst * dt (the wave-26 kWaitFloor shape)'),
        triggers=dict(
            shipped='clock lift slot + pads live (phi >= TOE_OFF && touching_prev_, latched)',
            a_absolute_envelope_cross=cross_abs, b_own_column_cross=cross_col,
            c_slot_first_live_tick=slot_fire, d_raw_slip_first_above_bound=slip_first,
            d_rejection_designed_residual_adm_runs=[dict(leg=a, beg=b, end=c) for a, b, c in adm_runs],
            e_hull_rejection='the loaded CoM-out-of-hull face is a continuous regime from tick 84 (38 ticks), no derivable threshold',
            ankle_wall_witness_rad_at_120=0.0032),
        calendar=dict(t_air_ticks=t_air,
                      predicted_R_fire=slot_fire['R'],
                      predicted_R_td=(slot_fire['R'] + t_air if slot_fire['R'] is not None else None),
                      predicted_L_slot_note='the L slot ~204 (the wave-16 derivation) measured on the clock series'),
        l_r_true_offset_series_example={str(t): dict(L=series[t]['L']['off'], R=series[t]['R']['off'])
                                        for t in ticks if t % 10 == 0 and t >= 60},
    )
    json.dump(out, open(sys.argv[3], 'w', encoding='utf-8'), indent=1)
    print(json.dumps(dict(off_td=OFF_TD, off_to=OFF_TO, v_bound=V_BOUND, v_worst=vw,
                          kfloor=KFLOOR, cross_abs=cross_abs, cross_col=cross_col,
                          slot_fire=slot_fire, slip_first=slip_first,
                          adm_runs=adm_runs, t_air=t_air), indent=1))


if __name__ == '__main__':
    main()
