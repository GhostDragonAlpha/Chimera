"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const {withProjectInstructions} = require("./compression-goal-helper.cjs");
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "chimera-compact-test-"));
const nested = path.join(dir, "child");
fs.mkdirSync(nested);
const runtime = {workingDirectory:nested,model:"unchanged",logger:{warn:()=>{}}};
const unchanged = JSON.stringify(runtime);
assert.equal(withProjectInstructions(runtime,"explicit"),"explicit");
fs.mkdirSync(path.join(dir,".zcode"));
const instruction = path.join(dir,".zcode","COMPACT_INSTRUCTIONS.md");
fs.writeFileSync(instruction,"Goal and purpose: preserve why the player's repair task matters.");
const combined = withProjectInstructions(runtime,"Keep task 42.");
assert.match(combined,/Goal and purpose/);
assert.match(combined,/Keep task 42/);
fs.writeFileSync(instruction,"Updated goal purpose");
assert.match(withProjectInstructions(runtime),/Updated goal purpose/);
fs.mkdirSync(path.join(nested,".zcode"));
const closer = path.join(nested,".zcode","COMPACT_INSTRUCTIONS.md");
fs.writeFileSync(closer,"Nearest instructions");
assert.equal(withProjectInstructions(runtime),"Nearest instructions");
fs.writeFileSync(closer,"x".repeat(16385));
assert.equal(withProjectInstructions(runtime,"explicit"),"explicit");
assert.equal(withProjectInstructions({},"explicit"),"explicit");
assert.equal(JSON.stringify(runtime),unchanged);
// Only the exact temporary directory created above is removed.
assert.equal(path.dirname(path.resolve(dir)), path.resolve(os.tmpdir()));
assert.ok(path.basename(dir).startsWith("chimera-compact-test-"));
fs.rmSync(dir,{recursive:true});
console.log("compression instructions: 8 checks PASS");
