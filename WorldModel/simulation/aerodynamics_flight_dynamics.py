def execute_aerodynamics_flight_dynamics_simulation(simulation_type: str, 
                                                   seed_value: int = 42) -> Dict[str, Any]:
    """
    Convenience function to execute aerodynamics and flight dynamics simulation.
    
    Args:
        simulation_type: 'thrust_vector_cog' or 'environmental_forces'
        seed_value: procedural seed for unique simulation generation
        
    Returns:
        simulated_flight_state: aerodynamics and flight dynamics results
    """
    simulator = AerodynamicsFlightDynamics(seed_value=seed_value)
    
    if simulation_type == "thrust_vector_cog":
        # Default parameters for thrust vector & CoG calculation
        results = simulator.calculate_thrust_vector_cog_dynamics(
            thrust_magnitude=50000.0,  # 50 kN thrust
            cog_x=0.0, cog_y=0.0, cog_z=0.0,  # CoG at origin
            ct_x=0.5, ct_y=0.0, ct_z=-2.0     # CT slightly offset
        )
    elif simulation_type == "environmental_forces":
        # Default parameters for environmental forces calculation
        results = simulator.calculate_environmental_forces(
            aircraft_mass=75000.0,  # Large commercial aircraft
            velocity=250.0,         # 250 m/s approx Mach 0.73
            altitude=10000.0,       # 10 km altitude
            wind_speed=30.0,        # 30 m/s wind
            wind_direction="headwind"
        )
    else:
        raise ValueError(f"Unknown simulation type: {simulation_type}")
        
    return {
        "simulation_status": "verified",
        "simulation_type": simulation_type,
        "aerodynamic_port_applied": True if simulation_type == "environmental_forces" else False,
        "gravitational_anchor_applied": True if simulation_type == "thrust_vector_cog" else False,
        "connection_shapes": ["Aerodynamic/Atmospheric Port", "Gravitational Anchor"],
        "metrics": results
    }
