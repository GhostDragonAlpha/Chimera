# Helpers
# ---------------------------------------------------------------------------

def _mirror_y(point: tuple[float, float, float]) -> tuple[float, float, float]:
    """Return the right-side copy of a left-side point."""
    x, y, z = point
    return (x, -y, z)


def _sub(a: tuple[float, float, float], b: tuple[float, float, float]) -> tuple[float, float, float]:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def _norm(v: tuple[float, float, float]) -> float:
    return math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2])


def _unit(v: tuple[float, float, float]) -> tuple[float, float, float]:
    n = _norm(v)
    if n < 1e-12:
        return (0.0, 0.0, 0.0)
    return (v[0] / n, v[1] / n, v[2] / n)


def _rope(
    name: str,
    anchor_a: str,
    anchor_b: str,
    point_a: tuple[float, float, float],
    point_b: tuple[float, float, float],
    kills_mode: str,
    slack_direction: str,
    antagonist_of: str | None,
) -> dict[str, Any]:
    """Build a rope record with a derived unit line-of-pull."""
    vec = _sub(point_b, point_a)
    unit = _unit(vec)
    return {
        "name": name,
        "anchor_a": anchor_a,
        "anchor_b": anchor_b,
        "anchor_a_point": point_a,
        "anchor_b_point": point_b,
        "line_of_pull_unit_vector": unit,
        "kills_mode": kills_mode,
        "slack_direction": slack_direction,
        "antagonist_of": antagonist_of,
        "law_citations": ["unique-stability", "no-prop", "anchor-on-bone-end"],
    }


def _pair(
    base_name: str,
    anchor_a: str,
    anchor_b: str,
    point_a_left: tuple[float, float, float],
    point_b_left: tuple[float, float, float],
    kills_mode: str,
    slack_direction: str,
    antagonist_of: str | None,
) -> list[dict[str, Any]]:
    """Generate left/right symmetric rope records."""
    return [
        _rope(
            f"{base_name}_L",
            anchor_a,
            anchor_b,
            point_a_left,
            point_b_left,
            kills_mode,
            slack_direction,
            antagonist_of + "_L" if antagonist_of else None,
        ),
        _rope(
            f"{base_name}_R",
            anchor_a,
            anchor_b,
            _mirror_y(point_a_left),
            _mirror_y(point_b_left),
            kills_mode,
            slack_direction,
            antagonist_of + "_R" if antagonist_of else None,
        ),
    ]


