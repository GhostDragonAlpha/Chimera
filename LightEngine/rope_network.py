"""
rope_network.py — Lane R standing-skeleton tension network.

This module is owned by the rope/tension lane. It defines the MINIMAL rope
set that makes the standing human skeleton's configuration the unique stable
equilibrium, expressed in a BODY-PLAN FRAME that is independent of
LightEngine/skeleton_scaling.py (Lane S). Integration with the assembly lane
comes later.

Body-plan frame
---------------
- origin: midpoint between ankle joint centers on the ground (z = 0).
- +x: anterior.
- +y: left lateral.
- +z: superior.
- H = 1.0 is normalized standing height.
- whole-body COM: (0.020, 0.000, 0.550).

Every rope record cites three settled laws:
  1. unique-stability  — theLeg v3 full-arc gate makes the loaded-side rope
     the pose selector and the unloaded-side rope a crumpling boundary.
  2. no-prop            — theTendon v4 / theLeg v3: rope is tension-only;
     slack_direction names the motion that lets it fold instead of prop.
  3. anchor-on-bone-end — socket v1 law: joints capture by wrapping the bone's
     END, so every anchor sits on an epiphysis / process / metaphysis.

The module uses only the Python standard library.
"""

