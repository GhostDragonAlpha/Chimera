"""
StandingHuman kinematic skeleton specification (Lane K1).

Builds a 77-link rigid-link tree from the existing scaling and structure lanes:
  - LightEngine/skeleton_scaling.scale_skeleton() provides bone geometry,
    mass fractions, and end-type tags.
  - LightEngine/skeleton_structures._body_instances() provides concrete left/right
    instances with proximal/distal endpoints and joint centers.
  - LightEngine/rope_network.py provides the 43 ligament/rope attachment points.

The tree is rooted at the sacrum (the chosen representative of the sacrum/pelvis
base; the two pelvic halves and the spine branch from it).  Every number is
marked ANATOMY-DATUM or DERIVED-GEOMETRY and cites its source.
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np

from LightEngine import skeleton_scaling, skeleton_structures
from LightEngine.rope_network import get_rope_network, VERTEBRAL_CENTERS
from LightEngine.constants import R_WALL


# ---------------------------------------------------------------------------
# Settled measured constants
# ---------------------------------------------------------------------------
# Joint capture band measured by prior cushion/joint experiments.
# Source: LightEngine/skeleton_scaling.D_EQ_LU and LightEngine.constants.R_WALL.
S_WALL_LU = R_WALL  # ANATOMY-DATUM: lower bound of the capture band.
D_EQ_LU = skeleton_scaling.D_EQ_LU  # ANATOMY-DATUM: upper bound / d_eq.

# DoF classes encoded from prior experimental verdicts.
BALL_CUP = "ball-cup"  # 3 rotational DoF
SADDLE = "saddle"      # 2 rotational DoF
HINGE = "hinge"        # 1 rotational DoF
SUTURE = "suture"      # 0 rotational DoF

_DOF_COUNT = {
    BALL_CUP: 3,
    SADDLE: 2,
    HINGE: 1,
    SUTURE: 0,
}


# ---------------------------------------------------------------------------
# Tree topology: child link -> (parent link, joint center key).
# ---------------------------------------------------------------------------
# DERIVED-GEOMETRY: each joint center key is a named point from
# LightEngine/skeleton_structures._joint_dict().  The parent is always the next
# link toward the sacrum, so the tree is setting-first from the standing load
# path.  Left/right pairs are generated by suffix substitution.
# ---------------------------------------------------------------------------

_LEVELS = [f"C{i}" for i in range(1, 8)] + \
          [f"T{i}" for i in range(1, 13)] + \
          [f"L{i}" for i in range(1, 6)]


def _spine_topology() -> dict[str, tuple[str | None, str | None]]:
    """Return parent/joint mapping for the skull-spine-sacrum chain."""
    topo: dict[str, tuple[str | None, str | None]] = {
        "sacrum": (None, None),
    }
    # sacrum -> L5 -> L4 -> ... -> C2 -> C1 -> skull
    topo["vertebra_L5"] = ("sacrum", "S1")
    for i in range(len(_LEVELS) - 1):
        lower = _LEVELS[i + 1]
        upper = _LEVELS[i]
        topo[f"vertebra_{upper}"] = (f"vertebra_{lower}", lower)
    topo["skull"] = ("vertebra_C1", "skull_suture")
    return topo


def _torso_topology() -> dict[str, tuple[str | None, str | None]]:
    """Return parent/joint mapping for ribs, sternum, shoulder girdle, arms."""
    topo: dict[str, tuple[str | None, str | None]] = {}
    for side in ("L", "R"):
        for n in range(1, 13):
            vert = f"T{min(n, 12)}"
            topo[f"rib_{side}_{n}"] = (f"vertebra_{vert}", vert)
        topo[f"scapula_{side}"] = (f"rib_{side}_1", f"rib_sternum_{side}_1")
        topo[f"humerus_{side}"] = (f"scapula_{side}", f"shoulder_{side}")
        topo[f"radius_ulna_{side}"] = (f"humerus_{side}", f"elbow_{side}")
        topo[f"hand_{side}"] = (f"radius_ulna_{side}", f"wrist_{side}")
    topo["sternum"] = ("vertebra_T1", "sternum_top")
    for side in ("L", "R"):
        topo[f"clavicle_{side}"] = ("sternum", "sternum_top")
    return topo


def _leg_topology() -> dict[str, tuple[str | None, str | None]]:
    """Return parent/joint mapping for pelvis and legs."""
    topo: dict[str, tuple[str | None, str | None]] = {}
    for side in ("L", "R"):
        topo[f"pelvis_{side}"] = ("sacrum", f"ilium_posterior_{side}")
        topo[f"femur_{side}"] = (f"pelvis_{side}", f"hip_{side}")
        topo[f"patella_{side}"] = (f"femur_{side}", f"knee_{side}")
        topo[f"tibia_{side}"] = (f"femur_{side}", f"knee_{side}")
        topo[f"fibula_{side}"] = (f"femur_{side}", f"knee_{side}")
        topo[f"tarsals_{side}"] = (f"tibia_{side}", f"ankle_{side}")
        topo[f"metatarsals_{side}"] = (f"tarsals_{side}", f"tarsal_{side}")
        topo[f"forefoot_{side}"] = (f"metatarsals_{side}", f"mtp_{side}")
    return topo


def _topology() -> dict[str, tuple[str | None, str | None]]:
    """Return the complete child -> (parent, joint_key) map."""
    topo: dict[str, tuple[str | None, str | None]] = {}
    topo.update(_spine_topology())
    topo.update(_torso_topology())
    topo.update(_leg_topology())
    return topo


# ---------------------------------------------------------------------------
# Local frame construction
# ---------------------------------------------------------------------------
def _orthonormal_basis(z_axis: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return right-handed orthonormal basis (x, y, z) with z = z_axis.

    DERIVED-GEOMETRY: z is the link's long axis.  y is the world lateral
    direction projected perpendicular to z (with a fallback to world anterior
    when the link is nearly vertical).  x completes the right-handed frame.
    This basis is the first approximation for all limb cross-sections; the
    demo battery will measure its error.
    """
    z = np.asarray(z_axis, dtype=np.float64).reshape(3)
    n = float(np.linalg.norm(z))
    if n < 1e-12:
        z = np.array([0.0, 0.0, 1.0], dtype=np.float64)
    else:
        z = z / n

    # Prefer world +y (left lateral) as the anatomical y reference.
    ref = np.array([0.0, 1.0, 0.0], dtype=np.float64)
    if abs(float(np.dot(z, ref))) > 0.9:
        ref = np.array([1.0, 0.0, 0.0], dtype=np.float64)

    y = ref - np.dot(ref, z) * z
    ny = float(np.linalg.norm(y))
    if ny < 1e-12:
        y = np.array([1.0, 0.0, 0.0], dtype=np.float64) if abs(z[0]) < 0.9 else \
            np.array([0.0, 1.0, 0.0], dtype=np.float64)
    else:
        y = y / ny

    x = np.cross(y, z)
    x = x / float(np.linalg.norm(x))
    return x, y, z


def _world_to_local_matrix(x: np.ndarray, y: np.ndarray, z: np.ndarray) -> np.ndarray:
    """Return the 3x3 rotation matrix R such that v_local = R @ v_world."""
    return np.vstack([x, y, z])


